begin;
select plan(35);

-- Settings logs are append-only and keep the salon referenced; this file tests
-- constraints and cascades, the logging itself is tested in 006.
alter table public.salons disable trigger salons_log_settings;
alter table public.salon_members disable trigger salon_members_log_settings;
alter table public.member_specialties disable trigger member_specialties_log_settings;
alter table public.opening_hours disable trigger opening_hours_log_settings;
alter table public.salon_closures disable trigger salon_closures_log_settings;
alter table public.services disable trigger services_log_settings;

select has_table('public', t, t || ' exists')
from unnest(array['salons', 'specialties', 'salon_members', 'member_specialties',
                  'opening_hours', 'salon_closures', 'services']) as t;
select is(
  (select count(*)::int from pg_class c join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relname in ('salons', 'specialties', 'salon_members',
     'member_specialties', 'opening_hours', 'salon_closures', 'services') and c.relrowsecurity),
  7, 'RLS is enabled on the seven tables'
);
select is((select count(*)::int from public.specialties), 10, 'the 10 specialties are seeded');

insert into auth.users (id, instance_id, aud, role) values
  ('00000000-0000-0000-0000-0000000000b1', '00000000-0000-0000-0000-000000000000', 'authenticated', 'authenticated'),
  ('00000000-0000-0000-0000-0000000000b2', '00000000-0000-0000-0000-000000000000', 'authenticated', 'authenticated');
insert into public.profiles (id, first_name) values
  ('00000000-0000-0000-0000-0000000000b1', 'Ely'),
  ('00000000-0000-0000-0000-0000000000b2', 'Ama');

create function pg_temp.new_salon(p_id uuid, p_slug text, p_extra text default '', p_phone text default '+33612345678')
returns void language plpgsql as $f$
begin
  execute format(
    $q$insert into public.salons (id, slug, name, phone, address_line, postal_code, city, location, siret, created_by %s)
       values (%L, %L, 'Salon Test', %L, '1 rue A', '75001', 'Paris',
               'SRID=4326;POINT(2.35 48.85)', '12345678901234', '00000000-0000-0000-0000-0000000000b1' %s)$q$,
    case when p_extra = '' then '' else ', ' || split_part(p_extra, '=', 1) end,
    p_id, p_slug, p_phone,
    case when p_extra = '' then '' else ', ' || split_part(p_extra, '=', 2) end);
end $f$;

select lives_ok($$select pg_temp.new_salon('10000000-0000-0000-0000-000000000001', 'salon-a')$$,
  'a minimal salon can be created');
select is((select status::text from public.salons where slug = 'salon-a'), 'draft', 'status defaults to draft');
select is((select queue_status::text from public.salons where slug = 'salon-a'), 'closed', 'queue_status defaults to closed');
select is((select reminder_after_minutes || '/' || auto_release_after_minutes from public.salons where slug = 'salon-a'), '5/10', 'reminder and release delays default to 5/10');
select ok((select length(qr_token) = 32 from public.salons where slug = 'salon-a'), 'a QR token is generated by default');

select throws_ok($$select pg_temp.new_salon('10000000-0000-0000-0000-000000000002', 'AB')$$, '23514', null, 'an invalid slug is rejected');
select throws_ok($$select pg_temp.new_salon('10000000-0000-0000-0000-000000000002', 'salon-a')$$, '23505', null, 'a duplicate slug is rejected');
select throws_ok($$select pg_temp.new_salon('10000000-0000-0000-0000-000000000002', 'salon-b', '', '0612345678')$$, '23514', null, 'a non E.164 phone is rejected');
select throws_ok($$select pg_temp.new_salon('10000000-0000-0000-0000-000000000002', 'salon-b', 'auto_release_after_minutes=5')$$, '23514', null, 'reminder must be shorter than auto release');
select throws_ok($$select pg_temp.new_salon('10000000-0000-0000-0000-000000000002', 'salon-b', 'end_of_day_warning_minutes=10')$$, '23514', null, 'end-of-day warning window is bounded to 30-240');
select lives_ok($$select pg_temp.new_salon('10000000-0000-0000-0000-000000000002', 'salon-b')$$, 'a second salon can be created');

-- salon_members
insert into public.salon_members (salon_id, profile_id, role, status, first_name, last_name, email)
values ('10000000-0000-0000-0000-000000000001', '00000000-0000-0000-0000-0000000000b1', 'manager', 'active', 'Ely', 'M', 'ely@example.com');
select throws_ok(
  $$insert into public.salon_members (salon_id, role, status, first_name, last_name, email)
    values ('10000000-0000-0000-0000-000000000001', 'stylist', 'active', 'Zoe', 'S', 'zoe@example.com')$$,
  '23514', null, 'an active member needs a profile');
select throws_ok(
  $$insert into public.salon_members (salon_id, role, first_name, last_name, email, is_hairdressing)
    values ('10000000-0000-0000-0000-000000000001', 'stylist', 'Zoe', 'S', 'zoe@example.com', false)$$,
  '23514', null, 'a stylist always cuts hair');
select throws_ok(
  $$insert into public.salon_members (salon_id, profile_id, role, status, first_name, last_name, email)
    values ('10000000-0000-0000-0000-000000000002', '00000000-0000-0000-0000-0000000000b1', 'manager', 'active', 'Ely', 'M', 'ely2@example.com')$$,
  '23505', null, 'a manager manages only one salon');
insert into public.salon_members (salon_id, role, first_name, last_name, email)
values ('10000000-0000-0000-0000-000000000001', 'stylist', 'Zoe', 'S', 'zoe@example.com');
select throws_ok(
  $$insert into public.salon_members (salon_id, role, first_name, last_name, email)
    values ('10000000-0000-0000-0000-000000000002', 'stylist', 'Zoe', 'S', 'ZOE@example.com')$$,
  '23505', null, 'a non-deactivated stylist belongs to one salon only');
select lives_ok(
  $$insert into public.member_specialties (member_id, specialty_code)
    select id, 'women_cut' from public.salon_members where email = 'zoe@example.com'$$,
  'a specialty can be attached to a member');
select throws_ok(
  $$insert into public.member_specialties (member_id, specialty_code)
    select id, 'unknown' from public.salon_members where email = 'zoe@example.com'$$,
  '23503', null, 'an unknown specialty is rejected');

-- opening_hours
insert into public.opening_hours (salon_id, weekday, opens_at, closes_at)
values ('10000000-0000-0000-0000-000000000001', 1, '09:00', '12:00');
select lives_ok(
  $$insert into public.opening_hours (salon_id, weekday, opens_at, closes_at)
    values ('10000000-0000-0000-0000-000000000001', 1, '14:00', '18:00')$$,
  'two ranges on the same day are allowed');
select throws_ok(
  $$insert into public.opening_hours (salon_id, weekday, opens_at, closes_at)
    values ('10000000-0000-0000-0000-000000000001', 1, '11:00', '15:00')$$,
  '23P01', null, 'overlapping ranges on the same day are rejected');
select throws_ok(
  $$insert into public.opening_hours (salon_id, weekday, opens_at, closes_at)
    values ('10000000-0000-0000-0000-000000000001', 2, '18:00', '09:00')$$,
  '23514', null, 'closing before opening is rejected');
select throws_ok(
  $$insert into public.opening_hours (salon_id, weekday, opens_at, closes_at)
    values ('10000000-0000-0000-0000-000000000001', 8, '09:00', '18:00')$$,
  '23514', null, 'a weekday above 7 is rejected');

-- salon_closures
select throws_ok(
  $$insert into public.salon_closures (salon_id, starts_on, ends_on)
    values ('10000000-0000-0000-0000-000000000001', '2026-12-26', '2026-12-24')$$,
  '23514', null, 'a closure cannot end before it starts');

-- services
select lives_ok(
  $$insert into public.services (salon_id, name, duration_minutes, price_cents, required_specialty_code)
    values ('10000000-0000-0000-0000-000000000001', 'Coupe femme', 45, 3500, 'women_cut')$$,
  'a service can be created');
select throws_ok(
  $$insert into public.services (salon_id, name, duration_minutes, price_cents)
    values ('10000000-0000-0000-0000-000000000001', 'Coupe', 42, 3500)$$,
  '23514', null, 'a duration that is not a multiple of 5 is rejected');
select throws_ok(
  $$insert into public.services (salon_id, name, duration_minutes, price_cents)
    values ('10000000-0000-0000-0000-000000000001', 'Coupe', 200, 3500)$$,
  '23514', null, 'a duration above 180 minutes is rejected');

-- cascade
delete from public.salons where id = '10000000-0000-0000-0000-000000000001';
select is(
  (select count(*)::int from public.salon_members where salon_id = '10000000-0000-0000-0000-000000000001')
  + (select count(*)::int from public.opening_hours where salon_id = '10000000-0000-0000-0000-000000000001')
  + (select count(*)::int from public.services where salon_id = '10000000-0000-0000-0000-000000000001'),
  0, 'deleting a salon cascades to members, hours and services'
);

select * from finish();
rollback;
